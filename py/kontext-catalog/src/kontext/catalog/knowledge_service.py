"""Durable OKF knowledge curation service.

This is the write/read surface for curated business context stored as OKF
concepts. It owns the ``.okf`` bundle (system of record) and projects concepts
into the disposable LanceDB ``knowledge`` scope so retrieval and agents can
find them.

The durable store holds only curation (prose, tags, and attestation) — never a
copy of catalog schema. Catalog/file details are hydrated at index time by
:class:`CatalogIndexService`, which keeps the durable layer free of anything
that would need to be synced with Iceberg.
"""

from __future__ import annotations

import asyncio
import re
from datetime import UTC, datetime

from kontext.common.protocols import AgentRuntimeStorageProviderProtocol
from kontext.okf import OkfAttestation, OkfConcept, OkfConceptStore, OkfProvenanceActor

from .indexing.catalog_index import CatalogIndexService

#: Knowledge-index scope holding curated OKF concepts.
_KNOWLEDGE_SCOPE = "knowledge"

#: Concept status for an agent proposal awaiting human review. Uses the OKF
#: v0.2 lifecycle vocabulary (``draft``); ``proposed`` is accepted as a legacy
#: alias for concepts curated before this alignment.
PROPOSED_STATUS = "draft"

#: Concept status once a human has verified and activated a concept. Uses the
#: OKF v0.2 lifecycle vocabulary (``stable``); ``active`` is treated as an
#: equivalent legacy value when reading older bundles.
ACTIVE_STATUS = "stable"

#: Legacy/alternate statuses recognized when listing proposals.
_PROPOSAL_STATUSES = frozenset({PROPOSED_STATUS, "proposed"})

_SLUG_PATTERN = re.compile(r"[^a-z0-9]+")


class OKFKnowledgeService:
    """Curate and retrieve OKF concepts for a single project."""

    def __init__(
        self,
        project_id: str,
        *,
        runtime_provider: AgentRuntimeStorageProviderProtocol | None = None,
    ) -> None:
        self.project_id = str(project_id)
        self._index_service = CatalogIndexService(
            self.project_id,
            runtime_provider=runtime_provider,
        )

    def _store(self) -> OkfConceptStore:
        return OkfConceptStore.for_project(self.project_id)

    async def list_concepts(self) -> list[OkfConcept]:
        return await asyncio.to_thread(self._store().list_concepts)

    async def get_concept(self, concept_id: str) -> OkfConcept | None:
        return await asyncio.to_thread(self._store().get_concept, concept_id)

    async def search_concepts(self, query: str, limit: int = 10) -> list[OkfConcept]:
        """Search curated concepts via the knowledge index, returning full concepts."""
        hits = await self._index_service.search_knowledge(
            query=query,
            limit=limit,
            scopes=[_KNOWLEDGE_SCOPE],
        )
        concepts: list[OkfConcept] = []
        store = self._store()
        for hit in hits:
            concept_id = str(hit.source_id or "").removeprefix(f"{_KNOWLEDGE_SCOPE}:")
            concept = store.get_concept(concept_id)
            if concept is not None:
                concepts.append(concept)
        return concepts

    async def upsert_concept(self, concept: OkfConcept) -> OkfConcept:
        """Persist a concept and refresh its knowledge-index projection."""
        store = self._store()
        await asyncio.to_thread(store.upsert_concepts, [concept])
        await self._refresh_index()
        return concept

    async def list_proposals(self) -> list[OkfConcept]:
        """Return concepts awaiting human review (agent proposals)."""
        concepts = await self.list_concepts()
        return [
            concept for concept in concepts if (concept.status or "").lower() in _PROPOSAL_STATUSES
        ]

    async def propose_concept(
        self,
        *,
        draft: OkfConcept,
        proposed_by: str,
        chat_session_id: str | None = None,
    ) -> OkfConcept:
        """Store an agent-drafted concept as a proposal awaiting human approval.

        The proposal is persisted with ``status='draft'`` and marked as
        generated by the agent. It is filtered out of retrieval by the OKF trust
        gate until a human approves it via :meth:`approve_concept`.
        """
        concept = OkfConcept(
            id=draft.id or _concept_id_for(draft),
            type=draft.type or "Note",
            title=draft.title or draft.id or _concept_id_for(draft),
            description=draft.description,
            resource=draft.resource,
            tags=list(draft.tags),
            body=draft.body,
            status=PROPOSED_STATUS,
            metadata={**dict(draft.metadata), "chat_session_id": chat_session_id},
            attestation=OkfAttestation(
                generated=(draft.attestation.generated if draft.attestation else None)
                or _provenance(proposed_by),
                verified=list(draft.attestation.verified) if draft.attestation else [],
            ),
        )
        return await self.upsert_concept(concept)

    async def approve_concept(
        self,
        concept_id: str,
        *,
        approved_by: str,
    ) -> OkfConcept | None:
        """Activate a proposed concept, recording human verification."""
        concept = await self.get_concept(concept_id)
        if concept is None:
            return None
        existing = list(concept.attestation.verified) if concept.attestation else []
        existing.append(_provenance(approved_by))
        attestation = (concept.attestation or OkfAttestation()).model_copy(
            update={"verified": existing}
        )
        approved = concept.model_copy(
            update={
                "status": ACTIVE_STATUS,
                "attestation": attestation,
            }
        )
        return await self.upsert_concept(approved)

    async def delete_concept(self, concept_id: str) -> bool:
        """Remove a concept (and its index projection). Returns whether it existed."""
        store = self._store()
        existing = await asyncio.to_thread(store.list_concepts)
        remaining = [concept for concept in existing if concept.id != concept_id]
        if len(remaining) == len(existing):
            return False
        await asyncio.to_thread(_rewrite_store, store, remaining)
        await self._refresh_index()
        return True

    async def _refresh_index(self) -> None:
        # Recreate the whole ``knowledge`` scope so deleted concepts cannot
        # linger as stale index documents. The corpus is small (hundreds of
        # concepts), so a full rebuild is cheap and always consistent.
        await self._index_service.index_knowledge(recreate=True)


def _rewrite_store(store: OkfConceptStore, concepts: list[OkfConcept]) -> None:
    """Rewrite the bundle to exactly ``concepts`` by clearing and re-upserting."""
    store.clear()
    store.upsert_concepts(list(concepts))


def _normalize_actor(actor: str) -> str:
    """Normalize an actor label to the OKF v0.2 convention.

    OKF prescribes ``human:<id>`` for people, ``process:<id>`` for automated
    processes, and ``<producer>/<version>`` for agent/tool producers. Kontext's
    auth layer emits ``User:<id>`` / ``ServiceAccount:<id>``; map those prefixes
    and leave already-conformant values (``human:``/``process:``/``*:*`` or a
    producer with a slash) untouched.
    """
    if ":" in actor:
        prefix, _, rest = actor.partition(":")
        if prefix.lower() == "user":
            return f"human:{rest}"
        if prefix.lower() == "serviceaccount":
            return f"process:{rest}"
    return actor


def _provenance(actor: str) -> OkfProvenanceActor:
    return OkfProvenanceActor(by=_normalize_actor(actor), at=datetime.now(UTC))


def _concept_id_for(draft: OkfConcept) -> str:
    slug = _SLUG_PATTERN.sub("-", (draft.title or "").lower()).strip("-")
    return f"concepts/{slug or 'untitled'}"


def coerce_concept(concept: OkfConcept) -> OkfConcept:
    """Return the canonical OKF concept model.

    ``kontext.okf`` re-exports the generated schema model, so this is an
    identity conversion today. It remains the single conversion point for the
    API and durable-store boundaries.
    """
    return concept


__all__ = ["OKFKnowledgeService", "coerce_concept"]
