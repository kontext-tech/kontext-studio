import {
   useApproveProposal,
   useDeleteConcept,
   useKnowledgeProposals
} from "@/features/knowledge/hooks/useKnowledge";
import {
   formatConceptDate,
   getGeneratedBy,
   getConceptTitle
} from "@/features/knowledge/utils/conceptPresentation";
import { CommonRoleGroups } from "@kontext-tech/auth";
import { PermissionButton } from "@kontext-tech/auth";
import { CheckOutlined, DeleteOutlined } from "@kontext-tech/icons";
import { LoadingSpinner } from "@kontext-tech/ui";
import { useUiApp } from "@kontext-tech/ui";
import { Alert, Button, Card, Empty, Flex, Space, Tag, Typography } from "antd";

interface ProposalsInboxProps {
   projectId?: string | null;
   onOpenConcept: (conceptId: string) => void;
}

const ProposalsInbox = ({ projectId, onOpenConcept }: ProposalsInboxProps) => {
   const { message, modal } = useUiApp();
   const proposalsQuery = useKnowledgeProposals(projectId);
   const approveProposal = useApproveProposal(projectId);
   const deleteConcept = useDeleteConcept(projectId);

   const handleApprove = async (conceptId: string) => {
      try {
         await approveProposal.mutateAsync(conceptId);
         message.success("Proposal approved and activated");
      } catch (error) {
         message.error(
            error instanceof Error
               ? error.message
               : "Failed to approve proposal"
         );
      }
   };

   const handleReject = (conceptId: string, title: string) => {
      modal.confirm({
         title: `Reject "${title}"?`,
         content:
            "This removes the agent proposal from the project's knowledge store.",
         okText: "Reject",
         okButtonProps: { danger: true },
         onOk: async () => {
            try {
               await deleteConcept.mutateAsync(conceptId);
               message.success("Proposal rejected");
            } catch (error) {
               message.error(
                  error instanceof Error
                     ? error.message
                     : "Failed to reject proposal"
               );
            }
         }
      });
   };

   if (proposalsQuery.isLoading) {
      return <LoadingSpinner />;
   }

   if (proposalsQuery.isError) {
      return (
         <Alert
            type="error"
            showIcon
            title="Failed to load proposals"
            description={
               proposalsQuery.error instanceof Error
                  ? proposalsQuery.error.message
                  : undefined
            }
         />
      );
   }

   const proposals = proposalsQuery.data ?? [];

   if (proposals.length === 0) {
      return (
         <Card>
            <Empty
               image={Empty.PRESENTED_IMAGE_SIMPLE}
               description="No proposals awaiting review. Agent-drafted concepts appear here."
            />
         </Card>
      );
   }

   return (
      <Space orientation="vertical" size="middle" style={{ width: "100%" }}>
         {proposals.map((concept) => {
            const conceptId = concept.id || "";
            const title = getConceptTitle(concept);
            const generatedBy = getGeneratedBy(concept);

            return (
               <Card key={conceptId} size="small">
                  <Flex align="flex-start" justify="space-between" gap="middle">
                     <Flex vertical gap={4} style={{ minWidth: 0 }}>
                        <Typography.Text strong>{title}</Typography.Text>
                        {concept.description && (
                           <Typography.Text type="secondary">
                              {concept.description}
                           </Typography.Text>
                        )}
                        <Space size="small" wrap>
                           <Tag>{concept.type}</Tag>
                           {generatedBy && (
                              <Tag color="blue">generated by {generatedBy}</Tag>
                           )}
                           {concept.attestation?.generated?.at && (
                              <Typography.Text type="secondary">
                                 {formatConceptDate(
                                    concept.attestation.generated.at
                                 )}
                              </Typography.Text>
                           )}
                        </Space>
                     </Flex>
                     <Space>
                        <Button
                           size="small"
                           onClick={() => onOpenConcept(conceptId)}
                        >
                           Review
                        </Button>
                        <PermissionButton
                           size="small"
                           type="primary"
                           icon={<CheckOutlined />}
                           loading={
                              approveProposal.isPending &&
                              approveProposal.variables === conceptId
                           }
                           allowedProjectRoles={
                              CommonRoleGroups.CONTENT_EDITORS
                           }
                           onClick={() => {
                              void handleApprove(conceptId);
                           }}
                        >
                           Approve
                        </PermissionButton>
                        <PermissionButton
                           size="small"
                           danger
                           icon={<DeleteOutlined />}
                           allowedProjectRoles={
                              CommonRoleGroups.CONTENT_EDITORS
                           }
                           onClick={() => handleReject(conceptId, title)}
                        >
                           Reject
                        </PermissionButton>
                     </Space>
                  </Flex>
               </Card>
            );
         })}
      </Space>
   );
};

export default ProposalsInbox;
