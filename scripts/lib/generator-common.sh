#!/bin/bash
# Shared helpers for the committed-code generators.
#
# Source this file; do not execute it directly. It centralizes the bits that
# every generator script needs: locating the repo root and asserting the
# required toolchain is present.

# Absolute path to the repository root, derived from this file's location.
generator_repo_root() {
    local lib_dir
    lib_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    cd "$lib_dir/../.." && pwd
}

require_command() {
    local cmd="$1"
    local hint="${2:-}"
    if ! command -v "$cmd" >/dev/null 2>&1; then
        echo "❌ Required command '$cmd' not found. $hint" >&2
        exit 1
    fi
}

# Assert the toolchain the generators rely on: openapi-typescript runs on
# Node, datamodel-codegen on Python.
verify_generator_prerequisites() {
    require_command node "Install Node.js (see .nvmrc)."
    require_command pnpm "Install pnpm >= 10 (corepack enable pnpm)."
    require_command uv "Install uv (https://docs.astral.sh/uv/)."

    echo "🔧 Pydantic models are generated by datamodel-code-generator (uv --group codegen)"
}
